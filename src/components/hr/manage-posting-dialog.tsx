"use client"

import { useState, useEffect } from "react"
import { Button } from "@/components/ui/button"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog"
import { Input } from "@/components/ui/input"
import { Label } from "@/components/ui/label"
import { Textarea } from "@/components/ui/textarea"
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select"
import { Badge } from "@/components/ui/badge"
import { Loader2 } from "lucide-react"
import { toast } from "sonner"
import { Switch } from "@/components/ui/switch"
import { generateJobPostingWithAiAction } from "@/app/hr/recruitment/ai-posting-actions"
import { saveJobPostingAction } from "@/app/hr/recruitment/actions"
import {
  WORK_MODE_LABELS,
  EMPLOYMENT_TYPE_LABELS,
  SENIORITY_LABELS,
} from "@/utils/hr/career-constants"
import { useCompany } from "@/contexts/company-context"
import { RichTextContent } from "@/components/rich-text-content"
import { cn } from "@/lib/utils"

export interface JobOptionItem {
  id: string
  megnevezes: string
  [key: string]: unknown
}

export interface PostingFormData {
  id?: string
  cim?: string
  munkakor_id?: string
  rovid_leiras?: string | null
  reszletes_leiras?: string | null
  is_internal?: boolean
  munkavegzes_modja?: string | null
  helyszin?: string | null
  foglalkoztatas_tipusa?: string | null
  tapasztalati_szint?: string | null
  reszleg_nev?: string | null
  bersav_min?: number | null
  bersav_max?: number | null
  bersav_publikus?: boolean
  jelentkezesi_hatarido?: string | null
  company_id?: string | null
  [key: string]: unknown
}

type CreationMode = "ai" | "manual"
type WizardStep = 1 | 2 | 3

const WIZARD_STEPS: { step: WizardStep; title: string; subtitle: string }[] = [
  {
    step: 1,
    title: "1. Módválasztás és Alapadatok",
    subtitle: "AI vagy saját kezű mód, cím és munkakör",
  },
  {
    step: 2,
    title: "2. Munkavégzés és Bérsáv",
    subtitle: "Mód, szint, helyszín és bértranszparencia",
  },
  {
    step: 3,
    title: "3. Pozícióleírás és Közzététel",
    subtitle: "Összefoglaló, részletes leírás és mentés",
  },
]

export function ManagePostingDialog({
  jobs,
  existingData = null,
  onSaved,
  children,
}: {
  jobs: JobOptionItem[]
  existingData?: PostingFormData | null
  onSaved: (data: PostingFormData) => void
  children?: React.ReactNode
}) {
  const { selectedCompany } = useCompany()
  const [open, setOpen] = useState(false)
  const [loading, setLoading] = useState(false)

  const isEditing = !!existingData

  // Lépcsős varázsló állapota
  const [currentStep, setCurrentStep] = useState<WizardStep>(1)
  const [creationMode, setCreationMode] = useState<CreationMode>(
    isEditing ? "manual" : "ai"
  )

  // 1. lépés mezői
  const [cim, setCim] = useState(existingData?.cim || "")
  const [munkakorId, setMunkakorId] = useState<string>(existingData?.munkakor_id || "")
  const [reszlegNev, setReszlegNev] = useState<string>(existingData?.reszleg_nev || "")
  const [jelentkezesiHatarido, setJelentkezesiHatarido] = useState<string>(
    existingData?.jelentkezesi_hatarido || ""
  )
  const [aiInstructions, setAiInstructions] = useState("")

  // 2. lépés mezői (Munkavégzés és Bértranszparencia)
  const [munkavegzesModja, setMunkavegzesModja] = useState<string>(
    existingData?.munkavegzes_modja || "hibrid"
  )
  const [helyszin, setHelyszin] = useState<string>(
    existingData?.helyszin || selectedCompany?.address || "Budapest"
  )
  const [foglalkoztatasTipusa, setFoglalkoztatasTipusa] = useState<string>(
    existingData?.foglalkoztatas_tipusa || "teljes_munkaido"
  )
  const [tapasztalatiSzint, setTapasztalatiSzint] = useState<string>(
    existingData?.tapasztalati_szint || "medior"
  )
  const [bersavMin, setBersavMin] = useState<string>(
    existingData?.bersav_min ? String(existingData.bersav_min) : ""
  )
  const [bersavMax, setBersavMax] = useState<string>(
    existingData?.bersav_max ? String(existingData.bersav_max) : ""
  )
  const [bersavPublikus, setBersavPublikus] = useState<boolean>(
    existingData?.bersav_publikus ?? false
  )

  // 3. lépés mezői (Leírások és AI generálás állapota)
  const [rovidLeiras, setRovidLeiras] = useState(existingData?.rovid_leiras || "")
  const [reszletesLeiras, setReszletesLeiras] = useState(
    existingData?.reszletes_leiras || ""
  )
  const [aiGenerating, setAiGenerating] = useState(false)
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false)
  const [descriptionViewMode, setDescriptionViewMode] = useState<"edit" | "preview">(
    "edit"
  )

  useEffect(() => {
    if (open) {
      setCurrentStep(1)
      setCreationMode(existingData ? "manual" : "ai")
      setCim(existingData?.cim || "")
      setMunkakorId(existingData?.munkakor_id || "")
      setRovidLeiras(existingData?.rovid_leiras || "")
      setReszletesLeiras(existingData?.reszletes_leiras || "")
      setMunkavegzesModja(existingData?.munkavegzes_modja || "hibrid")
      setHelyszin(existingData?.helyszin || selectedCompany?.address || "Budapest")
      setFoglalkoztatasTipusa(existingData?.foglalkoztatas_tipusa || "teljes_munkaido")
      setTapasztalatiSzint(existingData?.tapasztalati_szint || "medior")
      setReszlegNev(existingData?.reszleg_nev || "")
      setBersavMin(existingData?.bersav_min ? String(existingData.bersav_min) : "")
      setBersavMax(existingData?.bersav_max ? String(existingData.bersav_max) : "")
      setBersavPublikus(existingData?.bersav_publikus ?? false)
      setJelentkezesiHatarido(existingData?.jelentkezesi_hatarido || "")
      setAiInstructions("")
      setAiGenerating(false)
      setHasAutoGenerated(false)
      setDescriptionViewMode("edit")
    }
  }, [open, existingData, selectedCompany?.address])

  const selectedJobName = jobs.find((j) => j.id === munkakorId)?.megnevezes

  function handleJobChange(val: string | null) {
    if (!val) return
    setMunkakorId(val)
    const foundJob = jobs.find((j) => j.id === val)
    if (foundJob && !cim.trim()) {
      setCim(foundJob.megnevezes)
    }
  }

  function validateStep1(): boolean {
    if (!cim.trim()) {
      toast.error("Kérlek, add meg a hirdetés nyilvános címét!")
      return false
    }
    if (!munkakorId) {
      toast.error("Kérlek, válaszd ki a belső munkakört!")
      return false
    }
    return true
  }

  async function runAiGeneration(overwriteShort = false) {
    if (!cim.trim()) {
      toast.error("Kérlek, add meg a hirdetés nyilvános címét!")
      return
    }

    setAiGenerating(true)
    try {
      const result = await generateJobPostingWithAiAction({
        cim: cim.trim(),
        munkakorNev: selectedJobName,
        reszlegNev: reszlegNev.trim() || undefined,
        munkavegzesModja: WORK_MODE_LABELS[munkavegzesModja] || munkavegzesModja,
        foglalkoztatasTipusa:
          EMPLOYMENT_TYPE_LABELS[foglalkoztatasTipusa] || foglalkoztatasTipusa,
        tapasztalatiSzint: SENIORITY_LABELS[tapasztalatiSzint] || tapasztalatiSzint,
        helyszin: helyszin.trim() || selectedCompany?.address || undefined,
        bersavMin: bersavMin ? Number(bersavMin) : null,
        bersavMax: bersavMax ? Number(bersavMax) : null,
        bersavPublikus,
        jelentkezesiHatarido: jelentkezesiHatarido || null,
        instructions: aiInstructions.trim(),
        cegNev: selectedCompany?.name || undefined,
        cegCim: helyszin.trim() || selectedCompany?.address || undefined,
      })

      if (!result.success) {
        toast.error(result.error || "Hiba történt a generálás során.")
        return
      }

      if (result.reszletes_leiras) {
        setReszletesLeiras(result.reszletes_leiras)
      }
      if (result.rovid_leiras && (overwriteShort || !rovidLeiras.trim())) {
        setRovidLeiras(result.rovid_leiras)
      }

      setHasAutoGenerated(true)
      toast.success("Az AI összeállította a hirdetés szövegét a megadott paraméterek alapján.")
    } catch (err: unknown) {
      console.error(err)
      toast.error("Váratlan hiba történt az AI generáláskor.")
    } finally {
      setAiGenerating(false)
    }
  }

  function handleNextFromStep1() {
    if (!validateStep1()) return
    setCurrentStep(2)
  }

  async function handleNextFromStep2() {
    if (!validateStep1()) {
      setCurrentStep(1)
      return
    }
    setCurrentStep(3)
    if (creationMode === "ai" && !hasAutoGenerated && !reszletesLeiras.trim()) {
      await runAiGeneration(true)
    }
  }

  function handleStepClick(targetStep: WizardStep) {
    if (targetStep === currentStep) return
    if (targetStep > 1 && !validateStep1()) return
    setCurrentStep(targetStep)
    if (
      targetStep === 3 &&
      creationMode === "ai" &&
      !hasAutoGenerated &&
      !reszletesLeiras.trim()
    ) {
      void runAiGeneration(true)
    }
  }

  async function handleSubmit() {
    if (!validateStep1()) {
      setCurrentStep(1)
      return
    }

    setLoading(true)
    try {
      const res = await saveJobPostingAction({
        id: existingData?.id,
        cim: cim.trim(),
        munkakor_id: munkakorId,
        rovid_leiras: rovidLeiras.trim(),
        reszletes_leiras: reszletesLeiras.trim(),
        is_internal: existingData?.is_internal ?? false,
        munkavegzes_modja: munkavegzesModja,
        helyszin: helyszin.trim() || null,
        foglalkoztatas_tipusa: foglalkoztatasTipusa,
        tapasztalati_szint: tapasztalatiSzint,
        reszleg_nev: reszlegNev.trim() || null,
        bersav_min: bersavMin ? Number(bersavMin) : null,
        bersav_max: bersavMax ? Number(bersavMax) : null,
        bersav_publikus: bersavPublikus,
        jelentkezesi_hatarido: jelentkezesiHatarido || null,
        company_id: selectedCompany?.id || null,
      })

      if (res.error) {
        toast.error(res.error)
      } else if (res.data) {
        toast.success(isEditing ? "Álláshirdetés módosítva" : "Új álláshirdetés létrehozva")
        onSaved(res.data as PostingFormData)
        setOpen(false)
      }
    } catch (error: unknown) {
      toast.error("Hiba történt a mentés során")
      console.error(error)
    } finally {
      setLoading(false)
    }
  }

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger
        render={
          children ? (
            (children as React.ReactElement)
          ) : (
            <Button>Új hirdetés feladása</Button>
          )
        }
      />
      <DialogContent className="sm:max-w-[780px] max-h-[92vh] overflow-y-auto p-6">
        <DialogHeader className="pb-3 border-b border-border/60">
          <div className="flex items-center justify-between gap-2 flex-wrap pr-6">
            <DialogTitle className="text-lg font-semibold">
              {isEditing ? "Álláshirdetés módosítása" : "Új álláshirdetés feladása"}
            </DialogTitle>
            {selectedCompany?.name && (
              <Badge
                variant="outline"
                className="border-primary/30 bg-primary/5 text-primary text-xs font-medium"
              >
                Hirdető cég: {selectedCompany.name}
              </Badge>
            )}
          </div>
          <DialogDescription className="text-xs">
            Háromlépéses hirdetésfeladó folyamat: válaszd ki a készítési módot, állítsd be a pozíció paramétereit, majd véglegesítsd a leírást.
          </DialogDescription>

          {/* 3-Lépcsős Stepper Sáv */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-2 pt-3">
            {WIZARD_STEPS.map((item) => {
              const isActive = currentStep === item.step
              const isCompleted = currentStep > item.step
              return (
                <button
                  key={item.step}
                  type="button"
                  onClick={() => handleStepClick(item.step)}
                  className={cn(
                    "text-left rounded-md border px-3 py-2 transition-colors",
                    isActive
                      ? "border-primary bg-primary/10 text-foreground"
                      : isCompleted
                      ? "border-primary/40 bg-primary/5 text-foreground hover:border-primary/60"
                      : "border-border/60 bg-card/40 text-muted-foreground hover:border-primary/40"
                  )}
                >
                  <div className="flex items-center justify-between gap-1.5">
                    <span
                      className={cn(
                        "text-xs font-semibold",
                        isActive || isCompleted ? "text-primary" : "text-foreground/80"
                      )}
                    >
                      {item.title}
                    </span>
                    {isCompleted && (
                      <span className="text-[10px] font-medium uppercase tracking-wider text-primary">
                        Kész
                      </span>
                    )}
                  </div>
                  <p className="text-[11px] text-muted-foreground truncate mt-0.5">
                    {item.subtitle}
                  </p>
                </button>
              )
            })}
          </div>
        </DialogHeader>

        <div className="space-y-5 pt-2">
          {/* =========================================================
              1. LÉPÉS: MÓDVÁLASZTÁS ÉS POZÍCIÓ ALAPADATOK
             ========================================================= */}
          {currentStep === 1 && (
            <div className="space-y-4">
              {/* 1/A: AI Generálás vs. Saját kezű feladás választó */}
              <div className="space-y-2">
                <Label className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
                  Hogyan szeretnéd elkészíteni az álláshirdetést?
                </Label>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                  <button
                    type="button"
                    onClick={() => setCreationMode("ai")}
                    className={cn(
                      "text-left rounded-lg border p-3.5 transition-colors",
                      creationMode === "ai"
                        ? "border-primary bg-primary/5"
                        : "border-border/60 bg-card/50 hover:border-primary/40"
                    )}
                  >
                    <div className="flex items-center justify-between gap-2">
                      <span className="text-sm font-semibold text-foreground">
                        Generálás AI-val
                      </span>
                      <Badge
                        variant={creationMode === "ai" ? "default" : "outline"}
                        className="text-[10px] h-5"
                      >
                        Ajánlott
                      </Badge>
                    </div>
                    <p className="text-xs text-muted-foreground mt-1 leading-relaxed">
                      Az 1. és 2. lépésben megadott pozíció, munkakör, szint, munkavégzési mód és bérsáv alapján az AI automatikusan megírja a hirdetést.
                    </p>
                  </button>

                  <button
                    type="button"
                    onClick={() => setCreationMode("manual")}
                    className={cn(
                      "text-left rounded-lg border p-3.5 transition-colors",
                      creationMode === "manual"
                        ? "border-primary bg-primary/5"
                        : "border-border/60 bg-card/50 hover:border-primary/40"
                    )}
                  >
                    <div className="flex items-center justify-between gap-2">
                      <span className="text-sm font-semibold text-foreground">
                        Saját kezű álláshirdetés feladás
                      </span>
                      <Badge
                        variant={creationMode === "manual" ? "default" : "outline"}
                        className="text-[10px] h-5"
                      >
                        Manuális
                      </Badge>
                    </div>
                    <p className="text-xs text-muted-foreground mt-1 leading-relaxed">
                      A paraméterek beállítása után a 3. lépésben saját kezűleg írod meg vagy illeszted be a rövid összefoglalót és a részletes leírást.
                    </p>
                  </button>
                </div>
              </div>

              {/* 1/B: Cím, Munkakör, Részleg, Jelentkezési határidő */}
              <div className="rounded-lg border border-border/60 bg-card/60 p-4 space-y-4">
                <p className="text-xs font-semibold uppercase tracking-wider text-primary">
                  Pozíció megnevezése és szervezeti besorolás
                </p>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                  <div className="space-y-1.5">
                    <Label htmlFor="munkakor_id" className="text-xs font-medium">
                      Belső munkakör <span className="text-destructive">*</span>
                    </Label>
                    <Select
                      name="munkakor_id"
                      value={munkakorId}
                      onValueChange={handleJobChange}
                    >
                      <SelectTrigger className="w-full">
                        <SelectValue placeholder="Válassz munkakört...">
                          {selectedJobName}
                        </SelectValue>
                      </SelectTrigger>
                      <SelectContent>
                        {jobs.map((job) => (
                          <SelectItem key={job.id} value={job.id} label={job.megnevezes}>
                            {job.megnevezes}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  </div>

                  <div className="space-y-1.5">
                    <Label htmlFor="cim" className="text-xs font-medium">
                      Hirdetés nyilvános címe <span className="text-destructive">*</span>
                    </Label>
                    <Input
                      id="cim"
                      name="cim"
                      required
                      value={cim}
                      onChange={(e) => setCim(e.target.value)}
                      placeholder="pl. Senior Full-Stack Fejlesztő"
                    />
                  </div>
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                  <div className="space-y-1.5">
                    <Label htmlFor="reszleg_nev" className="text-xs font-medium">
                      Részleg / Csapat megnevezése (Karrieroldali szűrőhöz)
                    </Label>
                    <Input
                      id="reszleg_nev"
                      value={reszlegNev}
                      onChange={(e) => setReszlegNev(e.target.value)}
                      placeholder="Üresen hagyva a munkakör részlegét veszi át (pl. IT, HR, Pénzügy)"
                    />
                  </div>

                  <div className="space-y-1.5">
                    <Label htmlFor="jelentkezesi_hatarido" className="text-xs font-medium">
                      Jelentkezési határidő (opcionális)
                    </Label>
                    <Input
                      id="jelentkezesi_hatarido"
                      type="date"
                      value={jelentkezesiHatarido}
                      onChange={(e) => setJelentkezesiHatarido(e.target.value)}
                    />
                  </div>
                </div>
              </div>

              {/* 1/C: AI iránymutatás közvetlenül az 1. lépésben (ha AI mód aktív) */}
              {creationMode === "ai" && (
                <div className="rounded-lg border border-primary/30 bg-primary/5 p-4 space-y-2">
                  <div className="flex items-center justify-between gap-2">
                    <Label
                      htmlFor="ai_instructions_step1"
                      className="text-xs font-semibold uppercase tracking-wider text-primary"
                    >
                      Egyedi szempontok és kulcsszavak az AI számára (opcionális)
                    </Label>
                    <span className="text-[11px] text-muted-foreground">
                      A 3. lépésre lépve generálódik
                    </span>
                  </div>
                  <Textarea
                    id="ai_instructions_step1"
                    value={aiInstructions}
                    onChange={(e) => setAiInstructions(e.target.value)}
                    placeholder="Írd le röviden a főbb elvárásokat vagy technológiákat (pl. 4 év tapasztalat, React + Node.js, angol nyelvtudás, cafeteria)..."
                    className="min-h-[76px] text-xs bg-background"
                  />
                  <p className="text-[11px] text-muted-foreground">
                    Ha üresen hagyod, az AI a kiválasztott munkakör, a 2. lépésben megadott munkavégzési mód, tapasztalati szint és bérsáv alapján állítja össze a professzionális leírást.
                  </p>
                </div>
              )}
            </div>
          )}

          {/* =========================================================
              2. LÉPÉS: MUNKAVÉGZÉS MÓDJA, SZINT, HELYSZÍN ÉS BÉRSÁV
             ========================================================= */}
          {currentStep === 2 && (
            <div className="space-y-4">
              {/* 2/A: Munkavégzés módja, szint és helyszín */}
              <div className="rounded-lg border border-border/60 bg-card/60 p-4 space-y-4">
                <p className="text-xs font-semibold uppercase tracking-wider text-primary">
                  Munkavégzés módja, szint és helyszín
                </p>

                <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
                  <div className="space-y-1.5">
                    <Label className="text-xs font-medium">Munkavégzés módja</Label>
                    <Select
                      value={munkavegzesModja}
                      onValueChange={(val) => val && setMunkavegzesModja(val)}
                    >
                      <SelectTrigger className="w-full">
                        <SelectValue>{WORK_MODE_LABELS[munkavegzesModja]}</SelectValue>
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="hibrid">{WORK_MODE_LABELS.hibrid}</SelectItem>
                        <SelectItem value="remote">{WORK_MODE_LABELS.remote}</SelectItem>
                        <SelectItem value="irodai">{WORK_MODE_LABELS.irodai}</SelectItem>
                      </SelectContent>
                    </Select>
                  </div>

                  <div className="space-y-1.5">
                    <Label className="text-xs font-medium">Foglalkoztatás jellege</Label>
                    <Select
                      value={foglalkoztatasTipusa}
                      onValueChange={(val) => val && setFoglalkoztatasTipusa(val)}
                    >
                      <SelectTrigger className="w-full">
                        <SelectValue>
                          {EMPLOYMENT_TYPE_LABELS[foglalkoztatasTipusa]}
                        </SelectValue>
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="teljes_munkaido">
                          {EMPLOYMENT_TYPE_LABELS.teljes_munkaido}
                        </SelectItem>
                        <SelectItem value="reszmunkaido">
                          {EMPLOYMENT_TYPE_LABELS.reszmunkaido}
                        </SelectItem>
                        <SelectItem value="vallalkozoi">
                          {EMPLOYMENT_TYPE_LABELS.vallalkozoi}
                        </SelectItem>
                        <SelectItem value="gyakornok">
                          {EMPLOYMENT_TYPE_LABELS.gyakornok}
                        </SelectItem>
                      </SelectContent>
                    </Select>
                  </div>

                  <div className="space-y-1.5">
                    <Label className="text-xs font-medium">Tapasztalati szint</Label>
                    <Select
                      value={tapasztalatiSzint}
                      onValueChange={(val) => val && setTapasztalatiSzint(val)}
                    >
                      <SelectTrigger className="w-full">
                        <SelectValue>{SENIORITY_LABELS[tapasztalatiSzint]}</SelectValue>
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="junior">{SENIORITY_LABELS.junior}</SelectItem>
                        <SelectItem value="medior">{SENIORITY_LABELS.medior}</SelectItem>
                        <SelectItem value="senior">{SENIORITY_LABELS.senior}</SelectItem>
                        <SelectItem value="lead">{SENIORITY_LABELS.lead}</SelectItem>
                      </SelectContent>
                    </Select>
                  </div>
                </div>

                <div className="space-y-1.5">
                  <Label htmlFor="helyszin" className="text-xs font-medium">
                    Munkavégzés helyszíne (Város / Iroda címe)
                  </Label>
                  <Input
                    id="helyszin"
                    value={helyszin}
                    onChange={(e) => setHelyszin(e.target.value)}
                    placeholder="pl. 1054 Budapest, Szabadság tér 7."
                  />
                </div>
              </div>

              {/* 2/B: EU Bértranszparencia (Publikus bérsáv) */}
              <div className="rounded-lg border border-border/60 bg-card/60 p-4 space-y-4">
                <div className="flex items-center justify-between gap-4">
                  <div>
                    <p className="text-xs font-semibold uppercase tracking-wider text-primary">
                      Bértranszparencia és Juttatási Sáv (EU 2023/970 irányelv)
                    </p>
                    <p className="text-[11px] text-muted-foreground mt-0.5">
                      Ha bekapcsolod a publikus megjelenítést, a jelöltek a karrieroldalon is látják a bruttó havi bérsávot.
                    </p>
                  </div>
                  <div className="flex items-center gap-2 shrink-0">
                    <Label
                      htmlFor="bersav_publikus"
                      className="text-xs font-medium cursor-pointer"
                    >
                      Publikus a karrieroldalon
                    </Label>
                    <Switch
                      id="bersav_publikus"
                      checked={bersavPublikus}
                      onCheckedChange={setBersavPublikus}
                    />
                  </div>
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                  <div className="space-y-1.5">
                    <Label htmlFor="bersav_min" className="text-xs font-medium">
                      Minimum bruttó alapbér (Ft / hó)
                    </Label>
                    <Input
                      id="bersav_min"
                      type="number"
                      min={0}
                      step={10000}
                      value={bersavMin}
                      onChange={(e) => setBersavMin(e.target.value)}
                      placeholder="pl. 850000"
                      className="tabular-nums"
                    />
                  </div>
                  <div className="space-y-1.5">
                    <Label htmlFor="bersav_max" className="text-xs font-medium">
                      Maximum bruttó alapbér (Ft / hó)
                    </Label>
                    <Input
                      id="bersav_max"
                      type="number"
                      min={0}
                      step={10000}
                      value={bersavMax}
                      onChange={(e) => setBersavMax(e.target.value)}
                      placeholder="pl. 1250000"
                      className="tabular-nums"
                    />
                  </div>
                </div>
              </div>
            </div>
          )}

          {/* =========================================================
              3. LÉPÉS: POZÍCIÓLEÍRÁS ÉS KÖZZÉTÉTEL
             ========================================================= */}
          {currentStep === 3 && (
            <div className="space-y-4">
              {/* Beállított paraméterek összegző sávja */}
              <div className="rounded-lg border border-border/60 bg-muted/20 p-3 flex flex-wrap items-center justify-between gap-2 text-xs">
                <div className="space-y-0.5">
                  <span className="font-semibold text-foreground">{cim || "–"}</span>
                  <span className="text-muted-foreground ml-2">
                    ({selectedJobName || "Nincs munkakör"})
                  </span>
                </div>
                <div className="flex flex-wrap items-center gap-1.5">
                  <Badge variant="outline" className="text-[11px] font-normal">
                    {WORK_MODE_LABELS[munkavegzesModja] || munkavegzesModja}
                  </Badge>
                  <Badge variant="outline" className="text-[11px] font-normal">
                    {SENIORITY_LABELS[tapasztalatiSzint] || tapasztalatiSzint}
                  </Badge>
                  <Badge variant="outline" className="text-[11px] font-normal">
                    {EMPLOYMENT_TYPE_LABELS[foglalkoztatasTipusa] || foglalkoztatasTipusa}
                  </Badge>
                  {bersavPublikus && (bersavMin || bersavMax) && (
                    <Badge
                      variant="outline"
                      className="text-[11px] font-normal border-primary/30 text-primary"
                    >
                      Publikus bérsáv
                    </Badge>
                  )}
                </div>
              </div>

              {/* Beágyazott AI Vezérlősáv (nincs külön felugró modál) */}
              <div className="rounded-lg border border-primary/30 bg-primary/5 p-3.5 space-y-2.5">
                <div className="flex items-center justify-between gap-3 flex-wrap">
                  <div>
                    <p className="text-xs font-semibold text-primary">
                      AI Hirdetésszöveg-generátor
                    </p>
                    <p className="text-[11px] text-muted-foreground">
                      Az 1. és 2. lépésben megadott pozíció-, munkavégzési és bérsáv-adatok alapján készíti el a szövegezést.
                    </p>
                  </div>
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    disabled={aiGenerating}
                    onClick={() => runAiGeneration(true)}
                    className="h-8 text-xs font-medium border-primary/40 text-primary hover:bg-primary/10"
                  >
                    {aiGenerating ? (
                      <>
                        <Loader2 className="w-3.5 h-3.5 animate-spin mr-1.5" />
                        <span>AI fogalmazza a hirdetést...</span>
                      </>
                    ) : reszletesLeiras.trim() ? (
                      "Újragenerálás AI-val"
                    ) : (
                      "Generálás AI-val most"
                    )}
                  </Button>
                </div>

                <div className="space-y-1">
                  <Input
                    value={aiInstructions}
                    onChange={(e) => setAiInstructions(e.target.value)}
                    disabled={aiGenerating}
                    placeholder="Opcionális kulcsszavak finomításhoz (pl. React, 4 év tapasztalat, angol nyelv, cafeteria)..."
                    className="h-8 text-xs bg-background"
                  />
                </div>
              </div>

              {aiGenerating ? (
                <div className="rounded-lg border border-border/60 bg-card/60 p-8 text-center space-y-2">
                  <Loader2 className="w-5 h-5 animate-spin text-primary mx-auto" />
                  <p className="text-sm font-semibold text-foreground">
                    Az AI összeállítja a rövid összefoglalót és a strukturált pozícióleírást...
                  </p>
                  <p className="text-xs text-muted-foreground">
                    A generálás figyelembe veszi a pozíció nevét ({cim}), a munkakört ({selectedJobName}), a munkavégzés módját és a tapasztalati szintet.
                  </p>
                </div>
              ) : (
                <div className="space-y-3">
                  <div className="space-y-1.5">
                    <Label htmlFor="rovid_leiras" className="text-xs font-medium">
                      Rövid összefoglaló (a pozíciókártyán megjelenő leírás)
                    </Label>
                    <Textarea
                      id="rovid_leiras"
                      name="rovid_leiras"
                      value={rovidLeiras}
                      onChange={(e) => setRovidLeiras(e.target.value)}
                      placeholder="1-2 mondatos lényegretörő összefoglaló a pozícióról..."
                      maxLength={240}
                      className="min-h-[64px] text-xs"
                    />
                  </div>

                  <div className="space-y-1.5">
                    <div className="flex items-center justify-between gap-2">
                      <Label htmlFor="reszletes_leiras" className="text-xs font-medium">
                        Részletes pozícióleírás (HTML vagy Markdown)
                      </Label>
                      <div className="inline-flex rounded-md border border-border/60 bg-muted/30 p-0.5">
                        <button
                          type="button"
                          onClick={() => setDescriptionViewMode("edit")}
                          className={cn(
                            "px-2.5 py-1 text-[11px] font-medium rounded-sm transition-colors",
                            descriptionViewMode === "edit"
                              ? "bg-background text-foreground"
                              : "text-muted-foreground hover:text-foreground"
                          )}
                        >
                          Szerkesztés
                        </button>
                        <button
                          type="button"
                          onClick={() => setDescriptionViewMode("preview")}
                          className={cn(
                            "px-2.5 py-1 text-[11px] font-medium rounded-sm transition-colors",
                            descriptionViewMode === "preview"
                              ? "bg-background text-foreground"
                              : "text-muted-foreground hover:text-foreground"
                          )}
                        >
                          Formázott előnézet
                        </button>
                      </div>
                    </div>

                    {descriptionViewMode === "edit" ? (
                      <Textarea
                        id="reszletes_leiras"
                        name="reszletes_leiras"
                        value={reszletesLeiras}
                        onChange={(e) => setReszletesLeiras(e.target.value)}
                        className="min-h-[210px] font-mono text-xs leading-relaxed"
                        placeholder="Rólunk, Főbb feladatok, Elvárások, Amit kínálunk..."
                      />
                    ) : (
                      <div className="rounded-md border border-border/60 bg-card/40 p-4 min-h-[210px] max-h-[320px] overflow-y-auto">
                        <RichTextContent
                          content={reszletesLeiras}
                          fallback={
                            <p className="text-xs text-muted-foreground">
                              Még nincs megadva részletes pozícióleírás.
                            </p>
                          }
                        />
                      </div>
                    )}
                  </div>
                </div>
              )}
            </div>
          )}

          {/* =========================================================
              LÁBLÉC: LÉPÉS NAVIGÁCIÓ ÉS MENTÉS
             ========================================================= */}
          <div className="flex items-center justify-between pt-3 border-t border-border/60">
            <div>
              {currentStep > 1 && (
                <Button
                  type="button"
                  variant="outline"
                  disabled={loading || aiGenerating}
                  onClick={() =>
                    setCurrentStep((prev) => (prev > 1 ? ((prev - 1) as WizardStep) : 1))
                  }
                >
                  Előző lépés
                </Button>
              )}
            </div>

            <div className="flex items-center gap-2">
              <Button
                type="button"
                variant="outline"
                disabled={loading || aiGenerating}
                onClick={() => setOpen(false)}
              >
                Mégsem
              </Button>

              {currentStep === 1 && (
                <Button type="button" onClick={handleNextFromStep1}>
                  Tovább a munkavégzéshez és bérsávhoz
                </Button>
              )}

              {currentStep === 2 && (
                <Button
                  type="button"
                  disabled={aiGenerating}
                  onClick={handleNextFromStep2}
                >
                  {creationMode === "ai" && !hasAutoGenerated && !reszletesLeiras.trim()
                    ? "Tovább és generálás AI-val"
                    : "Tovább a pozícióleíráshoz"}
                </Button>
              )}

              {currentStep === 3 && (
                <Button
                  type="button"
                  disabled={loading || aiGenerating}
                  onClick={handleSubmit}
                >
                  {loading
                    ? "Mentés..."
                    : isEditing
                    ? "Módosítások mentése"
                    : "Álláshirdetés létrehozása"}
                </Button>
              )}
            </div>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  )
}
